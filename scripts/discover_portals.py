"""One-off: find which ATS (Greenhouse/Lever/Ashby) each candidate company uses; write config/portals.yml.
Usage: .venv/Scripts/python scripts/discover_portals.py [extra-names.txt]"""
from __future__ import annotations

import re
import sys
import time
from pathlib import Path

import requests
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from jobsearch.sources.ats import PARAMS, URLS  # noqa: E402
from jobsearch.sources.http import UA  # noqa: E402

CANDIDATES = [
    "Cloudflare", "Datadog", "Elastic", "GitLab", "Okta", "1Password", "Tailscale", "Wiz", "Snyk", "Vanta",
    "Drata", "Abnormal Security", "Huntress", "Red Canary", "Expel", "Arctic Wolf", "Rapid7", "Tenable",
    "SentinelOne", "Netskope", "Sumo Logic", "Axonius", "ReliaQuest", "Material Security", "Chainguard",
    "Anthropic", "OpenAI", "Zapier", "Automattic", "HashiCorp", "Grafana Labs", "Mozilla", "Canonical",
    "DuckDuckGo", "Sprout Social", "Workato", "Celigo", "Coinbase", "Stripe", "Twilio", "Dropbox",
    "Airtable", "Notion", "Figma", "Asana", "Discord", "Reddit", "Ramp", "Vercel", "Supabase",
]


def slugs(name: str) -> list[str]:
    base = re.sub(r"[^a-z0-9 ]", "", name.lower())
    out = [base.replace(" ", ""), base.replace(" ", "-"), base.split()[0]]
    return list(dict.fromkeys(s for s in out if s))


def job_count(ats: str, slug: str) -> int:
    try:
        r = requests.get(URLS[ats].format(slug=slug), params=PARAMS[ats], headers={"User-Agent": UA}, timeout=20)
        if r.status_code != 200:
            return 0
        data = r.json()
        return len(data) if isinstance(data, list) else len(data.get("jobs", []))
    except (requests.RequestException, ValueError):
        return 0


def main() -> None:
    names = list(CANDIDATES)
    if len(sys.argv) > 1:
        names += [l.strip() for l in Path(sys.argv[1]).read_text(encoding="utf-8").splitlines() if l.strip()]
    portals = []
    for name in dict.fromkeys(names):
        hit = None
        for ats in ("greenhouse", "ashby", "lever"):
            for slug in slugs(name):
                n = job_count(ats, slug)
                time.sleep(0.3)
                if n:
                    hit = {"name": name, "ats": ats, "slug": slug, "jobs_at_discovery": n}
                    break
            if hit:
                break
        print(f"{name:22} -> {hit['ats'] + '/' + hit['slug'] if hit else 'not found'}")
        if hit:
            portals.append(hit)
    out = Path(__file__).resolve().parent.parent / "config" / "portals.yml"
    header = "# Generated by scripts/discover_portals.py — edit freely; rerun to refresh.\n"
    out.write_text(header + yaml.safe_dump({"portals": portals}, sort_keys=False), encoding="utf-8")
    print(f"wrote {len(portals)} portals to {out}")


if __name__ == "__main__":
    main()
